#!/usr/bin/env node
/**
 * СТУПЕНЬ 2 РЕШЕНИЯ ПО ТРЕДУ `074-parallelism-and-domains` (слово john 2026-09-02):
 * шаг CI против ОДНОГО класса столкновений — исключительных ресурсов.
 *
 * ЧТО ЭТО ЗА КЛАСС И ПОЧЕМУ ТОЛЬКО ОН. Замер (`docs/collision-audit.md`) насчитал за две
 * недели 62 ТЕКСТОВЫХ столкновения и всего 4 по исключительному ресурсу. Против 62
 * механизма нет и не заводится: они сидят в `cli.ts`, README пакета и
 * `docs/protocol-reference.md` — файлах, куда по дисциплине дописывает КАЖДЫЙ предмет,
 * и объявить их исключительными значит запретить параллельную работу вообще. А вот
 * четыре — другой род: два пакета взяли ОДИН номер версии схемы, и один из этих случаев
 * (#123, тред `053-review-bypassed`) стоил не минут, а пропущенного круга ревью. Цена
 * тут не линейная, поэтому дверь ставится ровно сюда.
 *
 * ЧТО ШАГ СПРАШИВАЕТ: «этот PR тронул исключительный файл, а в базе этот же файл уехал
 * вперёд с момента ответвления — и ветка его НЕ подтянула?» Да — красный прогон с ИМЕНЕМ
 * файла. Не «конфликт возможен» вообще, а поимённо: что тронуто, где разошлось, что
 * сделать (подтянуть базу). Дверь, из которой не видно, что чинить, — дефект (карточка
 * `dev-core`, п. 4 дисциплины).
 *
 * ЧЕГО ШАГ НЕ ДЕЛАЕТ, и это граница, а не пробел:
 * - он НЕ читает содержимое (номер схемы не парсится). Два PR могли тронуть
 *   `version.ts` в разных местах — шаг всё равно скажет «подтяни». Это намеренно
 *   грубее и честнее разбора номера: список файлов не врёт, а разбор номера пришлось бы
 *   держать синхронным с формой файла;
 * - он НЕ ловит два ОТКРЫТЫХ PR, которые оба взяли один номер и ни один ещё не влит:
 *   пока в базе ничего не уехало, сравнивать не с чем. Ровно это закрывает СТУПЕНЬ 1
 *   (номер берётся поздно, перед меткой), и порядок ступеней в решении john не
 *   случайный: без ступени 1 шаг ловит вторую половину класса, а не весь;
 * - он НЕ трогает остальные PR: не тронул исключительный файл — шаг молчит и зеленеет.
 *
 * СПИСОК ИСКЛЮЧИТЕЛЬНЫХ ФАЙЛОВ ДЕРЖИТСЯ КОРОТКИМ И ВЫВЕДЕННЫМ ИЗ ЗАМЕРА (слово john):
 * сегодня в нём заслуженно два предмета — номер схемы и конфиг протокола. Воркфлоу,
 * замок зависимостей, карточки — добавляются, КОГДА СТОЛКНУТСЯ, а не из осторожности:
 * каждый лишний пункт здесь — это перебазировка, которую кто-то заплатит зря, а
 * перебазировка стоит нового круга ревью (§4.3 замера).
 *
 * Форма: `node scripts/exclusive-freshness.mjs --repo <корень> --base <ref> --head <ref>`.
 * Коды выхода — весь договор с вызывающим: 0 — чисто, 1 — исключительный файл разошёлся,
 * 2 — спросить не удалось (нет ref, не git, нет общего предка).
 */
import { execFileSync } from "node:child_process";

/**
 * Исключительные ресурсы. ПУТИ ТОЧНЫЕ, без масок: маска — это приглашение расширить
 * список молча, а каждое расширение здесь платится чужой перебазировкой.
 */
const EXCLUSIVE = [
  "agent-protocol.json",
  "packages/agent-protocol/src/schema/version.ts",
  "packages/agent-protocol/src/schema/migrate.ts",
];

const flag = (name, fallback) => {
  const i = process.argv.indexOf(`--${name}`);
  return i === -1 ? fallback : process.argv[i + 1];
};

/**
 * Вердикт — пересечение трёх списков, и он назван отдельной функцией, чтобы его было
 * видно целиком. ПРОВЕРЯЕТСЯ ОН ВСЁ РАВНО ЧЕРЕЗ ПРОЦЕСС, а не импортом: юнит на это
 * пересечение доказал бы арифметику множеств, а весь риск здесь — в СТЫКЕ с git
 * (какой ref чем является на `pull_request`, считается ли merge-base на shallow-клоне).
 * Поэтому тест — `exclusive-freshness.process.test.ts`, на настоящем репозитории.
 */
const staleExclusive = ({ touched, movedInBase, exclusive = EXCLUSIVE }) =>
  exclusive.filter((p) => touched.includes(p) && movedInBase.includes(p));

const git = (repo, args) =>
  execFileSync("git", ["-C", repo, ...args], {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  }).trim();

const names = (repo, range) =>
  git(repo, ["diff", "--name-only", range]).split("\n").filter(Boolean);

const main = () => {
  const repo = flag("repo", process.cwd());
  const base = flag("base");
  const head = flag("head", "HEAD");
  if (!base) {
    process.stderr.write("exclusive-freshness: не назван --base (ref базы PR)\n");
    return 2;
  }
  let mergeBase;
  try {
    mergeBase = git(repo, ["merge-base", base, head]);
  } catch (e) {
    // ПРИЧИНА НАЗЫВАЕТСЯ, А НЕ ГЛОТАЕТСЯ: чаще всего это shallow-клон (у merge-base нет
    // общего предка на глубине 1) — то есть чинится `fetch-depth: 0`, и это надо сказать.
    process.stderr.write(
      `exclusive-freshness: не считается общий предок \`${base}\` и \`${head}\` — ` +
        `нужен полный клон (fetch-depth: 0) и притянутая база. ${String(e.message ?? e).trim()}\n`,
    );
    return 2;
  }
  const touched = names(repo, `${mergeBase}..${head}`);
  const movedInBase = names(repo, `${mergeBase}..${base}`);
  const stale = staleExclusive({ touched, movedInBase });
  if (stale.length === 0) {
    const mine = EXCLUSIVE.filter((p) => touched.includes(p));
    process.stdout.write(
      mine.length === 0
        ? "exclusive-freshness: исключительных файлов этот PR не трогает — не спрашиваю.\n"
        : `exclusive-freshness: тронуто (${mine.join(", ")}), в базе с момента ответвления не уезжало — чисто.\n`,
    );
    return 0;
  }
  // ИМЯ ДОЕЗЖАЕТ ДО АННОТАЦИИ PR, а не только в лог шага: сводка показывает у упавшего
  // шага «exit code 1», то есть ровно тот отказ, из которого нельзя понять, что чинить.
  process.stdout.write(
    `::error::исключительный ресурс разошёлся: ${stale.join(", ")} — ` +
      `эти файлы уехали в \`${base}\` после ответвления ветки, а ветка их не подтянула. ` +
      "Так берутся два одинаковых номера схемы (тред 074, класс 2). Подтяните базу " +
      `(\`git merge ${base}\` или перебазировка) и повторите прогон.\n`,
  );
  return 1;
};

process.exit(main());
