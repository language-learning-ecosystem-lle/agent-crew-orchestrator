#!/usr/bin/env bash
# Проверка забора операторской руки (тред 062, постановка curator 2026-09-05).
#
# ЧТО ИМЕННО ПРОВЕРЯЕТСЯ. Не «скрипт разобрал аргументы», а ровно то, что стоило
# полуприменённой правки 2026-09-05: чужое дерево ДОЛЖНО отказать, и отказ обязан назвать
# имя владельца, имя работающего и форму «сделай это целиком из-под владельца». Дверь,
# которая молчит или отказывает безымянно, хуже отсутствующей: за ней человек в час аварии.
#
# ПОЧЕМУ ЧУЖОЙ ВЛАДЕЛЕЦ ПОДДЕЛЫВАЕТСЯ ПОДМЕНОЙ `stat`, А НЕ `chown`. `chown` на чужого
# пользователя требует root, а тест обязан идти и в CI, и из-под роли. Подменяется ровно
# тот внешний ответ, ради которого дверь стоит (владелец пути и кто ты), — сама ветвь
# отказа при этом гоняется настоящая, из того файла, который поедет на ящик. Тем же
# приёмом (`id`) проверяется ветвь «ты под root».
#
# Прогон руками: bash scripts/operator-tree-guard.test.sh
# В сюите он же поднимается процессом:
#   packages/agent-protocol/src/operator-tree-guard.process.test.ts
set -uo pipefail

cd "$(dirname "$0")"
GUARD="$PWD/operator-tree-guard.sh"

FAILED=0
check() { # <что> <ожидалось> <получено>
  if [ "$2" = "$3" ]; then
    echo "ok   · $1"
  else
    echo "FAIL · $1: ожидалось '$2', получено '$3'"
    FAILED=1
  fi
}
contains() { # <что> <подстрока> <текст>
  case "$3" in
    *"$2"*) echo "ok   · $1" ;;
    *)
      echo "FAIL · $1: в выводе нет '$2'"
      echo "--- вывод ---"
      echo "$3"
      echo "-------------"
      FAILED=1
      ;;
  esac
}

DIR="$(mktemp -d)"
trap 'rm -rf "$DIR"' EXIT
mkdir -p "$DIR/tree" "$DIR/bin"

# Вывод и код кладутся в OUT/RC переменными, а не через $(…): подстановка команд —
# подоболочка, и присвоенный в ней код возврата до проверок бы не доехал.
run() { # <путь…>
  PATH="$SHIM_PATH" bash "$GUARD" "$@" >"$DIR/out" 2>&1
  RC=$?
  OUT="$(cat "$DIR/out")"
}

# --- (1) своё дерево: пропускает и называет владельца ------------------------------------
SHIM_PATH="$PATH"
run "$DIR/tree"
check "своё дерево — код 0" "0" "$RC"
contains "своё дерево — сказано 'это ты'" "это ты" "$OUT"

# --- (2) файла ещё нет: судит ближайший существующий предок -------------------------------
run "$DIR/tree/nested/.npmrc"
check "несуществующий файл в своём дереве — код 0" "0" "$RC"
contains "несуществующий файл — назван предок" "$DIR/tree" "$OUT"

# --- (3) чужое дерево: отказ ПО ИМЕНИ ------------------------------------------------------
cat >"$DIR/bin/stat" <<'EOF'
#!/usr/bin/env bash
echo "4242 lang-hetzner"
EOF
chmod +x "$DIR/bin/stat"
SHIM_PATH="$DIR/bin:$PATH"
run "$DIR/tree"
check "чужое дерево — код 1" "1" "$RC"
contains "чужое дерево — назван владелец" "lang-hetzner" "$OUT"
contains "чужое дерево — назван работающий" "а ты \`$(id -un)\`" "$OUT"
contains "чужое дерево — дана форма перехода" "sudo -u lang-hetzner env PATH=" "$OUT"
contains "чужое дерево — назван запрет редактора" "ни редактором" "$OUT"
contains "чужое дерево — назван адрес правила" "docs/box-setup.md §0b" "$OUT"

# --- (4) под root: отказ до всякого чтения путей -------------------------------------------
cat >"$DIR/bin/id" <<'EOF'
#!/usr/bin/env bash
case "${1-}" in
  -u) echo 0 ;;
  -un) echo root ;;
  *) exit 3 ;;
esac
EOF
chmod +x "$DIR/bin/id"
run "$DIR/tree"
check "под root — код 1" "1" "$RC"
contains "под root — назван root" "под root" "$OUT"
rm -f "$DIR/bin/id" "$DIR/bin/stat"

# --- (5) ошибки вызова отличаются кодом от отказа ------------------------------------------
SHIM_PATH="$PATH"
run
check "без аргументов — код 2" "2" "$RC"
contains "без аргументов — сказано, чего нет" "не назван ни один путь" "$OUT"

run --help
check "--help — код 0" "0" "$RC"
contains "--help — печатает форму сцепки" "&& <команда>" "$OUT"

if [ "$FAILED" = "0" ]; then
  echo "ВСЕ ПРОВЕРКИ ПРОШЛИ"
else
  echo "ЕСТЬ ПАДЕНИЯ"
fi
exit "$FAILED"
