/**
 * `wake` — ВХОД РОЛИ В КОНТУР, СКАЗАННЫЙ ПАКЕТОМ (замер у потребителя, решение john
 * 2026-08-18: «такой инструкции, как wake, не место в обслуживаемом проекте»).
 *
 * Текст, объясняющий роли устройство почты, вахты и записи, обязан меняться ТЕМ ЖЕ
 * ходом, что команды, которые он называет. Пока он жил копией в обслуживаемом
 * проекте, это было не так, и цена измерена там же (замер curator, тред 087 §2):
 * инструкция велела исполнять пакет из чекаута, которого на ящике нет; называла
 * держателем merge роль, у которой его отобрали тремя неделями раньше; и посылала
 * читать вход из ПРОИЗВОДНОГО файла ровно там, где сама же объявляла принцип «вход
 * считается из источника». Ни одно из трёх не выдумано: каждое — расхождение текста
 * с кодом, который этот текст описывает.
 *
 * ПОЧЕМУ КОМАНДА, А НЕ ФАЙЛ В ПАКЕТЕ (кандидаты (а) и (в) постановки). Файл был бы
 * текстом, который потребитель ЦИТИРУЕТ: он не знает ни ветки почты, ни корня
 * чекаута, ни того, ждут ли эту роль треды прямо сейчас, — всё это факты конфига и
 * диска, то есть ровно то, из-за расхождения с чем предыдущая копия и умерла. Здесь
 * же значения подставляются из тех же источников, которыми живёт `mail`, а сам текст
 * попадает под CI репозитория-дома (`renderWake` — чистая функция, у неё тест).
 * Обёртка у потребителя после этого — одна строка вызова.
 *
 * ФОРМА ВЫЗОВА CLI — ЧУЖОЙ ФАКТ, и поэтому она параметр (`--as`): в одном проекте это
 * `pnpm -w protocol`, в другом — бинарь в PATH, в третьем — `tsx …/cli.ts`. Пакет,
 * печатающий свою форму вызова как единственную, врал бы всем, кроме одного ящика.
 */

/** Роль в терминах этого текста: id и файлы её карточки (поле `instructions`). */
export type WakeRole = {
  readonly id: string;
  /** Пути карточки роли из конфига; пусто — карточка не объявлена. */
  readonly instructions: readonly string[];
};

export type WakeFacts = {
  readonly role: WakeRole;
  /** Чем зовётся CLI у потребителя — `--as`, по умолчанию имя бинаря. */
  readonly cli: string;
  /** Ref, по которому читается конфиг: он же уезжает в печатаемые команды. */
  readonly ref: string;
  /** Абсолютный путь корня почты (каталог `agent-comms`). */
  readonly mailRoot: string;
  /** Ветка почты из конфига — не константа проекта. */
  readonly mailBranch: string;
  /** Треды, ждущие роль, в порядке очереди (R5). */
  readonly threads: readonly string[];
  /** Что прочитать не удалось — строки уже с причиной (065.4). */
  readonly unreadable: readonly string[];
};

const call = (cli: string, rest: string): string => `${cli} ${rest}`;

/**
 * Текст входа. Чистая функция: всё, что она знает о мире, приехало аргументом —
 * поэтому её проверяет обычный юнит, а не живой ящик.
 */
export const renderWake = (facts: WakeFacts): string => {
  const { cli, ref, mailRoot, mailBranch, role } = facts;
  const lines: string[] = [];

  lines.push(`Ты — роль ${role.id} в протоколе agent-comms.`);
  lines.push("");
  lines.push(
    role.instructions.length === 0
      ? "Карточка роли в конфиге не объявлена (поле `instructions` пусто) — спроси, прежде чем действовать по догадке."
      : `Карточка роли — эти файлы, в порядке чтения: ${role.instructions.join(", ")}. Зону и права бери из конфига командами, а не глазами из файла.`,
  );
  lines.push("");
  lines.push(
    `Почта живёт в ветке \`${mailBranch}\`, её корень на этом ящике — \`${mailRoot}\`. Оба факта прочитаны из конфига; в рабочем дереве роли этих файлов нет.`,
  );
  lines.push(
    "Вход считается ИЗ ТРЕДОВ, а не из производного `INDEX.md`: падение генератора реестра не должно ослеплять вход.",
  );
  lines.push("");

  if (facts.threads.length > 0) {
    lines.push(`## Почта для ${role.id} — ${facts.threads.length} тред(ов), в порядке очереди`);
    lines.push("");
    for (const id of facts.threads) lines.push(`- ${id}`);
    lines.push("");
    lines.push("По каждому разговору, начиная с первого:");
    lines.push("");
    lines.push(
      `1. прочитай его КОМАНДОЙ — \`${call(cli, `thread show --thread <id> --for ${role.id} --ref ${ref} --root ${mailRoot}\``)} (\`--tail <n>\`, если он длинный). \`--for\` называет, сколько в треде НОВОГО ДЛЯ ТЕБЯ — всё после твоего собственного последнего письма: в один тред могут писать две роли сразу, и последнее сообщение тогда не есть состояние разговора. Она называет и вложения папки треда;`,
    );
    lines.push("2. отработай постановку;");
    lines.push(
      `3. ответь сообщением в конец треда — \`${call(cli, `new-message --thread <id> --from ${role.id} --expects <e> --waiting-on <кто отвечает> --body-file <p> --write\``)}. \`--write\` означает ОТПРАВЛЕНО: файл, коммит и push — одно действие.`,
    );
  } else {
    lines.push(`## Почты для ${role.id} нет`);
    lines.push("");
    lines.push(
      "Ни один тред тебя сейчас не ждёт. Вахта — штатный режим ожидания, а не простой: встань на неё, если контур не поднял тебя под конкретную задачу.",
    );
  }

  if (facts.unreadable.length > 0) {
    lines.push("");
    lines.push("**Прочитано не всё** — список выше не полон, и вот чем именно он сужен:");
    lines.push("");
    for (const line of facts.unreadable) lines.push(`- ${line}`);
  }

  lines.push("");
  lines.push("## Правила, которые действуют всегда");
  lines.push("");
  lines.push(
    `- **Устройство протокола — \`PROTOCOL.md\`, форма команд — README пакета, раздел «Commands»**: второго описания формы нет ни у кого, включая этот текст. Что роли можно и где её зона — \`${call(cli, `roles list --ref ${ref}`)}\` и \`${call(cli, `config check --ref ${ref}`)}\`, а не чтение конфига глазами: файл с диска показал бы правку из своей ветки как действующую.`,
  );
  lines.push(
    "- **Производные файлы (`_thread.md`, `INDEX.md`) руками не правятся** — их пересобирает генератор из источника. Номер `## msg-NNN` — витрина генератора; идентичность сообщения — имя его файла.",
  );
  lines.push(
    "- **`--waiting-on` — РОВНО ОДНА роль**: ход держит один. Человек в это поле не принимается — «нужно решение человека» есть ход того, кто несёт вопрос.",
  );
  lines.push(
    "- **Тело сообщения кладётся файлом ВНЕ чекаута почты и вне рабочего дерева роли** (свой `mktemp -d`): доставка делает `reset --hard` при отклонённом push, а грязное дерево роли — отказ её следующего запуска.",
  );
  lines.push(
    "- **Нужен ввод посреди задачи — скажи и жди, не умирай с вопросом**: `new-message --await-input --write`, затем блокирующая `await-input`. Ответ читает ТА ЖЕ сессия, дерево остаётся нетронутым.",
  );
  lines.push(
    "- **Ожидание чужого прогона — не действие**: вердикт ревьюера и исход CI приходят в тред событием и будят роль штатно. Ход по своему PR — сообщение «жду по #N, голова `SHA`» и передача хода, а не опрос в цикле.",
  );
  lines.push(
    "- **Передача хода завершает прогон**: сессия после этого не просыпается. Заканчивать надо либо блокирующим ожиданием СВОЕГО ввода, либо отчётом в тред с передачей хода.",
  );

  return `${lines.join("\n")}\n`;
};
